// Regenerates src/ui/entities.js from the WHATWG list of named character references.
//   node scripts/entities.js
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://html.spec.whatwg.org/entities.json';
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'ui', 'entities.js');
const LINE = 100;

const response = await fetch(SOURCE);
assert.ok(response.ok, `fetching ${SOURCE} answered ${response.status}`);
const all = await response.json();
// CommonMark only decodes references closed by a semicolon.
const names = Object.keys(all).filter((key) => key.endsWith(';')).sort();
assert.ok(names.length > 2000, `${SOURCE} lists only ${names.length} references`);

const ascii = (s) => s.replace(/[^\x20-\x7e]/gu, (c) => [...c].map((u) => `\\u{${u.codePointAt(0).toString(16)}}`).join(''));
const entries = names.map((key) => {
  const name = key.slice(1, -1);
  assert.match(name, /^[A-Za-z][A-Za-z0-9]{1,31}$/, `${key} is not a plain reference name`);
  return `${name}:'${ascii(all[key].characters.replace(/\\/g, '\\\\').replace(/'/g, "\\'"))}'`;
});

const lines = [];
let line = ' ';
for (const entry of entries) {
  if (line.length + entry.length + 2 > LINE) { lines.push(line.trimEnd()); line = ' '; }
  line += ` ${entry},`;
}
lines.push(line.trimEnd());

writeFileSync(OUT, [
  `// Every HTML5 named character reference, from ${SOURCE}.`,
  '// Generated by scripts/entities.js; do not edit by hand.',
  'export const ENTITIES = Object.freeze({',
  ...lines,
  '});',
  '',
].join('\n'));
console.log(`wrote ${names.length} references to ${OUT}`);
